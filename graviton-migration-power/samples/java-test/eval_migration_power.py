# --- Custom code-based scorers ---

@scorer
def detects_docker_image_issues(outputs: dict) -> Feedback:
    """Check if the report flags the alpine Docker images as incompatible."""
    report = outputs.get("report", "")
    report_lower = report.lower()

    alpine_flagged = "alpine" in report_lower and any(
        term in report_lower for term in ["not support", "incompatible", "x86", "replace", "no arm", "lacks arm"]
    )
    suggests_fix = any(
        term in report_lower for term in ["eclipse-temurin:17-jdk", "eclipse-temurin:17-jre", "multi-arch"]
    )

    score = (1 if alpine_flagged else 0) * 0.5 + (1 if suggests_fix else 0) * 0.5
    return Feedback(value=score, rationale=f"Alpine flagged: {alpine_flagged}, Fix suggested: {suggests_fix}")


@scorer
def detects_netty_issue(outputs: dict) -> Feedback:
    """Check if the report identifies the missing aarch_64 Netty classifier."""
    report = outputs.get("report", "")
    report_lower = report.lower()

    netty_mentioned = "netty" in report_lower
    classifier_issue = any(
        term in report_lower for term in ["linux-aarch_64", "aarch_64", "linux-aarch64", "arm64 classifier", "missing classifier"]
    )
    x86_only_noted = "x86_64" in report_lower or "x86-64" in report_lower

    score = sum([netty_mentioned, classifier_issue, x86_only_noted]) / 3
    return Feedback(value=score, rationale=f"Netty mentioned: {netty_mentioned}, Classifier issue identified: {classifier_issue}, x86-only noted: {x86_only_noted}")


@scorer
def detects_rocksdb_issue(outputs: dict) -> Feedback:
    """Check if the report flags RocksDB 5.18.4 as ARM64-incompatible."""
    report = outputs.get("report", "")
    report_lower = report.lower()

    rocksdb_mentioned = "rocksdb" in report_lower or "rocksdbjni" in report_lower
    version_issue = "5.18" in report_lower
    suggests_upgrade = any(
        term in report_lower for term in ["upgrade", "6.0", "7.", "newer version", "update"]
    )

    score = sum([rocksdb_mentioned, version_issue, suggests_upgrade]) / 3
    return Feedback(value=score, rationale=f"RocksDB mentioned: {rocksdb_mentioned}, Version noted: {version_issue}, Upgrade suggested: {suggests_upgrade}")


@scorer
def detects_leveldb_issue(outputs: dict) -> Feedback:
    """Check if the report flags LevelDB JNI as ARM64-incompatible."""
    report = outputs.get("report", "")
    report_lower = report.lower()

    leveldb_mentioned = "leveldb" in report_lower or "leveldbjni" in report_lower
    incompatible_noted = any(
        term in report_lower for term in ["x86", "no arm", "incompatible", "not available", "not support", "alternative"]
    )

    score = sum([leveldb_mentioned, incompatible_noted]) / 2
    return Feedback(value=score, rationale=f"LevelDB mentioned: {leveldb_mentioned}, Incompatibility noted: {incompatible_noted}")


@scorer
def no_false_positives(outputs: dict) -> Feedback:
    """Check that compatible deps are NOT flagged as incompatible."""
    report = outputs.get("report", "")
    report_lower = report.lower()

    false_positives = []
    compatible_deps = {
        "snappy": "snappy-java",
        "lz4": "lz4-java",
        "h2": "H2 Database",
        "jackson": "Jackson",
        "spring boot": "Spring Boot",
    }

    negative_markers = ["incompatible", "not support", "no arm", "replace", "upgrade", "lacks arm", "x86 only"]

    for key, name in compatible_deps.items():
        # Find mentions of this dep in the report
        idx = report_lower.find(key)
        if idx == -1:
            continue
        # Check surrounding context (200 chars) for negative markers
        context = report_lower[max(0, idx - 100):idx + 150]
        # But skip if context also contains "compatible" near the dep name
        if any(pos in context for pos in ["compatible", "no change", "no action", "supported", "safe"]):
            continue
        if any(marker in context for marker in negative_markers):
            false_positives.append(name)

    score = 1.0 if len(false_positives) == 0 else max(0, 1.0 - len(false_positives) * 0.25)
    rationale = "No false positives" if not false_positives else f"False positives: {', '.join(false_positives)}"
    return Feedback(value=score, rationale=rationale)


@scorer
def has_actionable_fixes(outputs: dict) -> Feedback:
    """Check that the report provides specific actionable fixes."""
    report = outputs.get("report", "")
    report_lower = report.lower()

    actions_found = []
    action_checks = {
        "Docker fix": any(t in report_lower for t in ["eclipse-temurin:17-jdk", "eclipse-temurin:17-jre", "multi-arch"]),
        "Netty fix": any(t in report_lower for t in ["linux-aarch_64", "aarch_64 classifier", "add.*classifier"]),
        "RocksDB fix": any(t in report_lower for t in ["upgrade", "6.0", "7.", "newer"]) and "rocksdb" in report_lower,
        "LevelDB fix": any(t in report_lower for t in ["alternative", "replace", "remove", "pure java"]) and "leveldb" in report_lower,
    }

    for action, found in action_checks.items():
        if found:
            actions_found.append(action)

    score = len(actions_found) / len(action_checks)
    return Feedback(value=score, rationale=f"Actionable fixes found: {', '.join(actions_found) if actions_found else 'None'}")


@scorer
def report_structure(outputs: dict) -> Feedback:
    """Check if the report has a clear organized structure."""
    report = outputs.get("report", "")
    report_lower = report.lower()

    structure_checks = {
        "Has summary/overview": any(t in report_lower for t in ["summary", "overview", "findings"]),
        "Has Docker section": any(t in report_lower for t in ["docker", "container image", "base image", "dockerfile"]),
        "Has dependencies section": any(t in report_lower for t in ["dependenc", "package", "library", "libraries"]),
        "Has recommendations": any(t in report_lower for t in ["recommend", "action", "fix", "next step", "resolution"]),
    }

    found = [k for k, v in structure_checks.items() if v]
    score = len(found) / len(structure_checks)
    return Feedback(value=score, rationale=f"Structure elements: {', '.join(found)}")


# --- Kiro CLI LLM-as-Judge scorers ---

@scorer
def kiro_correctness(inputs: dict, outputs: dict, expectations: dict) -> Feedback:
    """Use kiro-cli to judge factual correctness of the report against expectations."""
    report = outputs.get("report", "")
    expected = expectations.get("expected_response", "")

    prompt = f"""You are evaluating a migration report for correctness. 
Compare the report against the expected findings and score it.

EXPECTED FINDINGS:
{expected}

ACTUAL REPORT:
{report}

Score the report from 0.0 to 1.0 based on how correctly it identifies the issues.
- 1.0 = all expected issues found correctly, no false claims
- 0.5 = some issues found, some missed or incorrect
- 0.0 = completely wrong or empty

Start your response with the score as a decimal number (e.g. 0.85), then explain your reasoning."""

    return kiro_score(prompt)


@scorer
def kiro_completeness(inputs: dict, outputs: dict, expectations: dict) -> Feedback:
    """Use kiro-cli to judge migration analysis completeness."""
    report = outputs.get("report", "")

    prompt = f"""You are evaluating a Graviton migration report for completeness.

The report should cover:
1. Docker base images that lack ARM64 support (eclipse-temurin:17-jdk-alpine, eclipse-temurin:17-jre-alpine)
2. ALL dependencies with native x86-only code (netty x86_64 classifier, rocksdbjni 5.18.4, leveldbjni-all 1.8)
3. Correctly identify compatible deps WITHOUT flagging them (snappy-java, lz4-java, H2, Jackson, Spring Boot)
4. NOT recommend unnecessary changes for pure Java packages

REPORT TO EVALUATE:
{report}

Score from 0.0 to 1.0:
- 1.0 = identifies all 5 incompatible items AND correctly clears all compatible items
- 0.75 = identifies 4/5 incompatible items with no false positives
- 0.5 = identifies 3/5 or has some false positives
- 0.25 = identifies fewer than 3 or has many false positives
- 0.0 = fails to identify most issues

Start your response with the score as a decimal number (e.g. 0.85), then explain your reasoning."""

    return kiro_score(prompt)


@scorer
def kiro_actionability(inputs: dict, outputs: dict, expectations: dict) -> Feedback:
    """Use kiro-cli to judge whether fixes are specific and actionable."""
    report = outputs.get("report", "")

    prompt = f"""You are evaluating a Graviton migration report for actionability of its recommendations.

Every incompatible item must have a CONCRETE fix:
- Docker images: specific replacement image tag (e.g., eclipse-temurin:17-jdk)
- Netty: specific classifier to add (linux-aarch_64)
- RocksDB: specific version to upgrade to (6.2.2+)
- LevelDB: specific alternative named or clear statement about no ARM64 build

Vague suggestions like "check compatibility" or "consider alternatives" without specifics are NOT acceptable.

REPORT TO EVALUATE:
{report}

Score from 0.0 to 1.0:
- 1.0 = all fixes are specific with exact versions/names/commands
- 0.75 = most fixes are specific, one or two are vague
- 0.5 = mix of specific and vague recommendations
- 0.0 = all recommendations are vague or missing

Start your response with the score as a decimal number (e.g. 0.85), then explain your reasoning."""

    return kiro_score(prompt)


@scorer
def kiro_no_hallucinations(inputs: dict, outputs: dict, expectations: dict) -> Feedback:
    """Use kiro-cli to check for hallucinated/false positive issues."""
    report = outputs.get("report", "")

    prompt = f"""You are checking a Graviton migration report for hallucinated issues (false positives).

The following are KNOWN COMPATIBLE with ARM64 and must NOT be flagged as needing changes:
- snappy-java 1.1.10.5 (has ARM64 native libs since 1.1.4)
- lz4-java 1.8.0 (pure Java fallback + ARM64 native available)
- H2 Database (pure Java, fully portable)
- Jackson (pure Java, no native code)
- Spring Boot / JPA (pure Java framework)

If the report incorrectly flags ANY of these as ARM64-incompatible, that is a critical false positive.

REPORT TO EVALUATE:
{report}

Score from 0.0 to 1.0:
- 1.0 = no false positives, all compatible deps correctly identified as safe
- 0.75 = one minor false positive (e.g., a warning about a compatible dep)
- 0.5 = multiple false positives
- 0.0 = many false positives or compatible deps incorrectly flagged as broken

Start your response with the score as a decimal number (e.g. 0.85), then explain your reasoning."""

    return kiro_score(prompt)


# Combine all scorers
