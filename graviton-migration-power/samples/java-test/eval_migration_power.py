# ─── Kiro CLI LLM Judge ─────────────────────────────────────────────────────

KIRO_CLI = os.environ.get("KIRO_CLI_PATH", "kiro-cli")


def kiro_judge(prompt: str) -> str:
    """
    Use kiro-cli as an LLM judge. Sends a prompt via non-interactive mode
    and returns the response text (stripped of ANSI escape codes).
    """
    import re

    try:
        result = subprocess.run(
            [
                KIRO_CLI, "chat",
                "--no-interactive",
                "--trust-all-tools",
                prompt,
            ],
            capture_output=True,
            text=True,
            timeout=120,
        )
        if result.returncode != 0:
            return f"[kiro-cli error] returncode={result.returncode} stderr={result.stderr.strip()}"
        # Strip ANSI escape codes from output
        ansi_escape = re.compile(r'\x1b\[[0-9;]*[a-zA-Z]')
        clean = ansi_escape.sub('', result.stdout).strip()
        # Remove the leading "> " prompt marker if present
        if clean.startswith("> "):
            clean = clean[2:]
        return clean
    except subprocess.TimeoutExpired:
        return "[kiro-cli error] timeout after 120s"
    except FileNotFoundError:
        return f"[kiro-cli error] '{KIRO_CLI}' not found. Install kiro-cli or set KIRO_CLI_PATH."


def kiro_score(prompt: str) -> Feedback:
    """
    Ask kiro-cli to evaluate and return a Feedback object.
    Parses the score from the response - tries JSON first, then falls back
    to extracting a decimal number from natural language.
    """
    import re

    response = kiro_judge(prompt)

    if response.startswith("[kiro-cli error]"):
        return Feedback(value=0.0, rationale=response)

    # Try to parse JSON from the response
    try:
        json_str = response
        if "```json" in json_str:
            json_str = json_str.split("```json")[1].split("```")[0].strip()
        elif "```" in json_str:
            json_str = json_str.split("```")[1].split("```")[0].strip()

        parsed = json.loads(json_str)
        score = float(parsed.get("score", 0.0))
        justification = parsed.get("justification", "No justification provided")
        return Feedback(value=max(0.0, min(1.0, score)), rationale=justification)
    except (json.JSONDecodeError, ValueError, IndexError):
        pass

    # Fallback: extract a decimal number (0.0-1.0) from the response
    score_match = re.search(r'\b(0(?:\.\d+)?|1(?:\.0+)?)\b', response)
    if score_match:
        score = float(score_match.group(1))
        if 0.0 <= score <= 1.0:
            # Use first ~300 chars of response as rationale
            rationale = response[:300].replace('\n', ' ').strip()
            return Feedback(value=score, rationale=rationale)

    # Last resort: look for fraction like "4/5" or percentage
    frac_match = re.search(r'(\d+)\s*/\s*(\d+)', response)
    if frac_match:
        num, denom = int(frac_match.group(1)), int(frac_match.group(2))
        if denom > 0:
            score = min(1.0, num / denom)
            rationale = response[:300].replace('\n', ' ').strip()
            return Feedback(value=score, rationale=rationale)

    return Feedback(value=0.0, rationale=f"Could not parse score from response: {response[:300]}")


